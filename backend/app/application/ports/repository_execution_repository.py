from typing import Protocol
from uuid import UUID

from app.domain.entities.repository_execution import RepositoryExecution


class RepositoryExecutionRepository(Protocol):
    def add(self, item: RepositoryExecution) -> None: ...
    def get(self, identifier: UUID, execution_id: UUID | None = None, *, for_update: bool = False) -> RepositoryExecution | None: ...
    def get_by_project(self, execution_id: UUID, project_id: int) -> RepositoryExecution | None: ...
    def transition(self, item: RepositoryExecution, expected_status: str) -> bool: ...
    def save_summary(self, item: RepositoryExecution, expected_status: str = "running") -> bool: ...
    def list_for_execution(self, execution_id: UUID, *, page: int = 1, page_size: int = 25): ...
    def update_execution_counters(self, execution_id: UUID, **counters) -> bool: ...
