from typing import Protocol
from uuid import UUID
from app.domain.entities.mining_execution import MiningExecution, ExecutionStatus, TriggerType


class MiningExecutionRepository(Protocol):
    def add(self, execution: MiningExecution) -> None: ...
    def get(self, identifier: UUID, *, for_update: bool = False) -> MiningExecution | None: ...
    def active_for(self, configuration_id: UUID) -> MiningExecution | None: ...
    def transition(self, execution: MiningExecution, expected_status: ExecutionStatus) -> bool: ...
    def update_snapshot(self, execution: MiningExecution) -> bool: ...
    def update_counters(self, identifier: UUID, *, repository_count: int, successful_count: int,
                        failed_count: int, finding_count: int, scope_failures: int = 0,
                        repository_mining_completed: bool = False) -> bool: ...
    def page(self, *, page: int, page_size: int, configuration_id: UUID | None = None,
             status: ExecutionStatus | None = None, trigger_type: TriggerType | None = None) -> tuple[list[MiningExecution], int]: ...
